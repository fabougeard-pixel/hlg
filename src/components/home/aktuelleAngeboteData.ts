/**
 * Resolve Spotlight and 6 Deals for a given tab key by merging admin config over defaults.
 */
export function resolveTabOffers(tabKey: TabFilterKey, config?: any) {
  const base = DEFAULT_TAB_DATA[tabKey] || DEFAULT_TAB_DATA.ALL;
  const savedTab =
    tabKey === 'ALL'
      ? { spotlight: config?.spotlight, deals: config?.deals }
      : config?.tabsConfig?.[tabKey];

  const customSpot = savedTab?.spotlight;
  const spotlight: DealItem = customSpot
    ? {
        ...base.spotlight,
        ...customSpot,
        image: customSpot.image !== undefined ? customSpot.image : base.spotlight.image,
        rawPrice:
          customSpot.rawPrice ??
          (parseFloat(String(customSpot.price || '0').replace(/[^0-9,.]/g, '').replace(',', '.')) ||
            base.spotlight.rawPrice),
      }
    : base.spotlight;

  const customDeals = Array.isArray(savedTab?.deals) ? savedTab.deals : null;
  const deals: DealItem[] = base.deals.map((defItem, idx) => {
    const customItem = customDeals?.[idx];
    if (!customItem) return defItem;
    return {
      ...defItem,
      ...customItem,
      image: customItem.image !== undefined ? customItem.image : defItem.image,
      rawPrice:
        customItem.rawPrice ??
        (parseFloat(String(customItem.price || '0').replace(/[^0-9,.]/g, '').replace(',', '.')) ||
          defItem.rawPrice),
    };
  });

  return { spotlight, deals };
}

